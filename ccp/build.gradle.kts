// ── libphonenumber metadata footprint (Android) ────────────────────────────────────────────────
//
// The libphonenumber jar ships three metadata blobs. This library only ever reaches
// PhoneNumberUtil and AsYouTypeFormatter, which need exactly one of them:
//
//   PhoneNumberMetadataProto            ~235 KB  required
//   ShortNumberMetadataProto             ~75 KB  only ShortNumberInfo reads it   — unused here
//   PhoneNumberAlternateFormatsProto     ~23 KB  only PhoneNumberMatcher reads it — unused here
//
// So Android consumers can strip ~99 KB from their APK with a `packaging { resources { excludes } }`
// rule (see the README and :app for the exact snippet). That advice is only safe while the library
// genuinely avoids those two entry points — and "we currently don't use it" is the kind of fact
// that quietly stops being true. This task makes it a build failure instead.
val forbiddenPhoneNumberApis = listOf(
    "ShortNumberInfo" to "needs ShortNumberMetadataProto, which consumers are told to exclude",
    "PhoneNumberMatcher" to "needs PhoneNumberAlternateFormatsProto, which consumers are told to exclude",
    "PhoneNumberOfflineGeocoder" to "pulls in the separate geocoder metadata artifact",
    "PhoneNumberToCarrierMapper" to "pulls in the separate carrier metadata artifact",
)

val verifyPhoneNumberMetadataFootprint = tasks.register("verifyPhoneNumberMetadataFootprint") {
    description = "Fails if the library starts using libphonenumber APIs whose metadata consumers are told to strip."
    group = "verification"

    val sources = fileTree("src") {
        include("commonMain/kotlin/**/*.kt", "androidMain/kotlin/**/*.kt")
    }
    inputs.files(sources).withPathSensitivity(PathSensitivity.RELATIVE)
    // No real output; a marker keeps the task up-to-date-able instead of re-running every build.
    val marker = layout.buildDirectory.file("reports/phonenumber-footprint.txt")
    outputs.file(marker)
    val moduleDir = projectDir

    doLast {
        val violations = sources.files.flatMap { file ->
            val text = file.readText()
            forbiddenPhoneNumberApis.mapNotNull { (api, why) ->
                if (text.contains(api)) "${file.relativeTo(moduleDir)} uses $api — $why" else null
            }
        }
        if (violations.isNotEmpty()) {
            error(
                buildString {
                    appendLine("libphonenumber metadata footprint check failed.")
                    appendLine()
                    violations.forEach { appendLine("  • $it") }
                    appendLine()
                    appendLine("Either drop the usage, or remove the corresponding exclusion from the")
                    appendLine("README and :app packaging rules — consumers following that advice would")
                    appendLine("otherwise ship an app that fails at runtime with a missing-metadata error.")
                }
            )
        }
        marker.get().asFile.apply {
            parentFile.mkdirs()
            writeText("ok: none of ${forbiddenPhoneNumberApis.map { it.first }} are referenced\n")
        }
    }
}

tasks.named("check") { dependsOn(verifyPhoneNumberMetadataFootprint) }

// ── Translation parity ─────────────────────────────────────────────────────────────────────────
//
// The README claims the bundled locales are complete, and every one of them was — until three
// strings were added to values/ and the translations were not updated in the same change. A blanket
// "every locale must be complete" lint would also fire on a *new* locale that is still being filled
// in, which would make contributing a translation a chicken-and-egg problem.
//
// This is the narrower rule that is actually wanted: an existing locale must stay complete. A
// brand-new one is free to land partial, and is only held to parity once it declares a name.
//
// It also rejects the two Android-resource habits that Compose Multiplatform resources do not
// support, both of which fail silently instead of at build time: a non-positional `%s` / `%d` (only
// the `%1$s` form is substituted, so the raw placeholder would reach the screen), and an escaped
// `\'` or `\"` (only `\n`, `\t`, `\uXXXX` and `\\` are unescaped, so the backslash would show).
val verifyTranslationParity = tasks.register("verifyTranslationParity") {
    description = "Fails when a bundled locale is missing a string that values/ defines, or uses unsupported syntax."
    group = "verification"

    val resDir = layout.projectDirectory.dir("src/commonMain/composeResources")
    inputs.dir(resDir).withPathSensitivity(PathSensitivity.RELATIVE)
    val marker = layout.buildDirectory.file("reports/translation-parity.txt")
    outputs.file(marker)

    doLast {
        val nameRegex = Regex("""<(?:string|plurals|string-array) name="([^"]+)"""")
        fun namesIn(file: File) = nameRegex.findAll(file.readText()).map { it.groupValues[1] }.toSet()

        val root = resDir.asFile
        val base = namesIn(File(root, "values/strings.xml"))
        val localeFiles = root.listFiles()
            .orEmpty()
            .filter { it.isDirectory && it.name.startsWith("values") }
            .sortedBy { it.name }
            .map { File(it, "strings.xml") }
            .filter { it.exists() }

        val missingProblems = localeFiles
            .filter { it.parentFile.name != "values" }
            .mapNotNull { file ->
                val missing = (base - namesIn(file)).sorted()
                if (missing.isEmpty()) null
                else "${file.parentFile.name} is missing: ${missing.joinToString(", ")}"
            }

        val entryRegex = Regex("<(string|item)\\b[^>]*>(.*?)</\\1>", RegexOption.DOT_MATCHES_ALL)
        val nonPositionalArgument = Regex("%[sd]")
        val escapedQuote = Regex("\\\\['\"]")
        val syntaxProblems = localeFiles.flatMap { file ->
            entryRegex.findAll(file.readText()).mapNotNull { match ->
                val text = match.groupValues[2].trim()
                when {
                    nonPositionalArgument.containsMatchIn(text) ->
                        "${file.parentFile.name}: non-positional argument in \"$text\" (use %1\$s / %1\$d)"
                    escapedQuote.containsMatchIn(text) ->
                        "${file.parentFile.name}: escaped quote in \"$text\" (write ' and \" unescaped)"
                    else -> null
                }
            }.toList()
        }

        val problems = missingProblems + syntaxProblems

        if (problems.isNotEmpty()) {
            error(
                buildString {
                    appendLine("Translation parity check failed.")
                    appendLine()
                    problems.forEach { appendLine("  • $it") }
                    appendLine()
                    appendLine("Add missing entries (or remove a locale that is no longer maintained), and keep")
                    appendLine("strings positional and unescaped — see the comment at the top of values/strings.xml.")
                }
            )
        }
        marker.get().asFile.apply {
            parentFile.mkdirs()
            writeText("ok: every values-* locale covers all ${base.size} entries in values/\n")
        }
    }
}

tasks.named("check") { dependsOn(verifyTranslationParity) }
