// ── libPhoneNumber-iOS ─────────────────────────────────────────────────────────────────────────
//
// On iOS the phone-number engine is libPhoneNumber-iOS — the Objective-C port of the same Google
// library the Android target uses, generated from the same metadata release (see the lib-phone
// comment in gradle/libs.versions.toml). Its sources are vendored under src/nativeInterop and
// compiled per target into a static archive that cinterop embeds in the klib, so consumers get it
// with the dependency: nothing to add to their Podfile, Package.swift or linker flags.

/** The `xcrun --sdk` name and clang target triple for each Kotlin/Native iOS target. */
fun KonanTarget.appleToolchain(): Pair<String, String> = when (this) {
    KonanTarget.IOS_ARM64 -> "iphoneos" to "arm64-apple-ios15.0"
    KonanTarget.IOS_SIMULATOR_ARM64 -> "iphonesimulator" to "arm64-apple-ios15.0-simulator"
    else -> error("No libPhoneNumber-iOS toolchain mapping for $this")
}

fun KotlinNativeTarget.bindLibPhoneNumber() {
    val (sdk, triple) = konanTarget.appleToolchain()
    val outputDir = layout.buildDirectory.dir("libphonenumber/$targetName")
    val buildArchive = tasks.register<Exec>("buildLibPhoneNumber${targetName.replaceFirstChar(Char::uppercase)}") {
        description = "Compiles the vendored libPhoneNumber-iOS into a static archive for $targetName."
        group = "build"
        val script = rootProject.layout.projectDirectory.file("scripts/build-libphonenumber-ios.sh")
        inputs.file(script).withPathSensitivity(PathSensitivity.RELATIVE)
        inputs.dir(layout.projectDirectory.dir("src/nativeInterop")).withPathSensitivity(PathSensitivity.RELATIVE)
        outputs.dir(outputDir)
        commandLine(script.asFile.absolutePath, sdk, triple, outputDir.get().asFile.absolutePath)
    }

    compilations.getByName("main").cinterops.create("libPhoneNumber") {
        definitionFile.set(layout.projectDirectory.file("src/nativeInterop/cinterop/libPhoneNumber.def"))
        // ccp_libphonenumber.h (in cinterop/) applies the same renames the archive was compiled
        // with before importing the libPhoneNumber-iOS headers, so the bindings name the prefixed
        // symbols the archive actually defines (CCPNBPhoneNumberUtil, …).
        includeDirs(
            layout.projectDirectory.dir("src/nativeInterop/cinterop"),
            layout.projectDirectory.dir("src/nativeInterop/libPhoneNumber-iOS/libPhoneNumber"),
            layout.projectDirectory.dir("src/nativeInterop/libPhoneNumber-iOS/libPhoneNumberInternal"),
        )
        extraOpts("-libraryPath", outputDir.get().asFile.absolutePath)
        tasks.named(interopProcessingTaskName) { dependsOn(buildArchive) }
    }
}

// ── Publishing ─────────────────────────────────────────────────────────────────────────────────
//
// Coordinates, POM metadata and signing flags all come from gradle.properties (GROUP,
// VERSION_NAME, POM_*), so the version number has exactly one home and the docs site, the
// published artifact and the README cannot drift apart.
//
// One Gradle-metadata publication fans out to ccp-android (AAR) and ccp-iosarm64 /
// ccp-iossimulatorarm64 (klibs). Gradle consumers depend on `io.github.ezekielwachira:ccp` and get
// the right one per target. The iOS klibs can only be built on macOS, so releases run there.
mavenPublishing {
    configure(
        KotlinMultiplatform(
            javadocJar = JavadocJar.Dokka("dokkaGeneratePublicationHtml"),
            sourcesJar = SourcesJar.Sources(),
        )
    )

    // Signing keys only exist on the release runner. Signing unconditionally would make every
    // local `publishToMavenLocal` fail.
    if (providers.gradleProperty("signingInMemoryKey").isPresent) {
        signAllPublications()
    }
}

